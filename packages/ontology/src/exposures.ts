import type { Severity } from '@shc/shared';
import type { AttackPatternId, OwaspCategory, WeaknessId } from './standards';
import type { ComponentId, ControlId, RemediationId } from './vocabulary';

/**
 * An exposure is something we can observe about a site that gives an attacker an
 * advantage. Every finding a check emits points at exactly one exposure (or observation),
 * and through it at the weakness (CWE), the attack it enables (CAPEC), the controls that
 * reduce it and the remediations that remove it.
 */
export interface ExposureDef {
  kind: 'exposure' | 'observation';
  label: string;
  /** Plain-English explanation shown to site owners. */
  description: string;
  defaultSeverity: Severity;
  appliesTo: readonly ComponentId[];
  weaknesses: readonly WeaknessId[];
  enables: readonly AttackPatternId[];
  mitigatedBy: readonly ControlId[];
  remediatedBy: readonly RemediationId[];
  owasp: readonly OwaspCategory[];
  /** Evidence that the site may already be compromised. Always shown, even on the free plan. */
  indicatesCompromise?: boolean;
  /** Where this is detected: an external check module id, or 'plugin' for the inside view. */
  detectedBy: readonly string[];
}

const exposure = (def: Omit<ExposureDef, 'kind'>): ExposureDef => ({ kind: 'exposure', ...def });

